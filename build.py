"""Bundle public/ into src/worker.js (Wrangler's asset upload is blocked by the proxy here)."""
import json, os
TYPES = {'.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'application/javascript', '.jpg': 'image/jpeg', '.png': 'image/png'}
files = sorted(os.path.relpath(os.path.join(r, f), 'public') for r, _, fs in os.walk('public') for f in fs)
head, rows = [], []
for i, f in enumerate(files):
    ext = os.path.splitext(f)[1]
    if ext == '.js':  # embed as a string so it isn't bundled as Worker code
        head.append(f'const f{i} = {json.dumps(open("public/" + f).read())};')
    else:
        head.append(f'import f{i} from "../public/{f}";')
    rows.append(f'  "/{f}": [f{i}, "{TYPES[ext]}"],')
os.makedirs('src', exist_ok=True)
open('src/worker.js', 'w').write('// Generated by build.py — do not edit.\n' + '\n'.join(head) + '\nconst FILES = {\n' + '\n'.join(rows) + '''
};
export default {
  fetch(req) {
    let p = new URL(req.url).pathname;
    if (p === "/") p = "/index.html";
    const f = FILES[p];
    if (!f) return new Response("Not found", { status: 404 });
    return new Response(f[0], { headers: { "content-type": f[1], "cache-control": p.startsWith("/photos/") ? "public, max-age=86400" : "public, max-age=300" } });
  }
};
''')
